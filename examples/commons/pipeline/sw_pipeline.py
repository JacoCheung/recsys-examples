@dataclass
class ProfileResult:
    """Result of :meth:`TaskProfiler.profile`.

    Attributes:
        baseline_s:  median wall-clock time of one serial iteration (seconds).
        exposed_s:   ``{task_name: exposed_seconds}`` — how much wall-clock
                     time is *removed* from the baseline when that task is
                     shortcut (replaced by cached results).
    """

    baseline_s: float
    exposed_s: Dict[str, float]

    def print_report(self) -> None:
        bms = self.baseline_s * 1e3
        print(f"Baseline serial iteration: {bms:.3f} ms\n")
        hdr = f"  {'Task':<24} {'Exposed':>10} {'% baseline':>12}"
        print(hdr)
        print(f"  {'-' * 24} {'-' * 10} {'-' * 12}")
        total = 0.0
        for name, t in self.exposed_s.items():
            ms = t * 1e3
            pct = t / self.baseline_s * 100 if self.baseline_s > 0 else 0
            total += t
            print(f"  {name:<24} {ms:>8.3f}ms {pct:>10.1f}%")
        print(f"  {'-' * 24} {'-' * 10} {'-' * 12}")
        tms = total * 1e3
        tpct = total / self.baseline_s * 100 if self.baseline_s > 0 else 0
        print(f"  {'SUM':<24} {tms:>8.3f}ms {tpct:>10.1f}%")
        print(
            f"\n  (SUM > 100% means tasks overlap on the critical path;\n"
            f"   SUM < 100% means some wall-clock time is framework overhead)"
        )


class TaskProfiler:
    """Measure per-task **exposed time** for auto-scheduling.

    Delegates to :meth:`SWPipeline.enable_shortcut` /
    :meth:`SWPipeline.disable_shortcut` and
    :meth:`SWPipeline.run_one_serial_iter`, so the shortcut logic
    (caching, autograd-safe restore, sequencer advancement for
    globally-ordered tasks) is shared with runtime shortcutting.

    ::

        exposed_time(T) = baseline_serial - serial_with_T_shortcut

    Example::

        profiler = TaskProfiler(pipe)
        result = profiler.profile(batches, num_warmup=3, num_measure=10)
        result.print_report()
    """

    def __init__(self, pipeline: SWPipeline) -> None:
        self._pipe = pipeline

    def _timed_run(self, batch: Any, count: int) -> float:
        """Run *count* serial iterations with the same *batch*.

        Returns average wall-clock seconds per iteration.  Only two
        ``cuda.synchronize`` calls total (before and after).
        """
        pipe = self._pipe
        dev = pipe.device
        torch.cuda.synchronize(dev)
        t0 = time.perf_counter()
        for i in range(count):
            pipe.run_one_serial_iter(batch, i)
        torch.cuda.synchronize(dev)
        return (time.perf_counter() - t0) / count

    def profile(
        self,
        batch: Any,
        num_warmup: int = 3,
        num_measure: int = 10,
        num_rounds: int = 3,
    ) -> ProfileResult:
        """Profile exposed time for each task using a single representative batch.

        Four phases:

        1. **Warmup** — ``num_warmup`` normal serial iterations.
        2. **Baseline** — ``num_rounds`` rounds × ``num_measure``
           iterations; take median of per-round averages.
        3. **Per-task shortcut** — for each task *T*:

           a. ``enable_shortcut(T)`` + one caching iteration.
           b. ``num_rounds`` rounds × ``num_measure`` timed iterations.
           c. ``disable_shortcut(T)`` to restore normal mode.

        4. Compute ``exposed(T) = max(0, baseline - median_shortcut(T))``.

        Args:
            batch: a single batch (same format as ``next(data_iter)``).
            num_warmup: warmup iterations (not timed).
            num_measure: iterations per timed round.
            num_rounds: number of rounds (median of round-averages is taken).

        Returns:
            :class:`ProfileResult` with baseline and per-task exposed times.
        """
        import statistics

        pipe = self._pipe

        for _ in range(num_warmup):
            pipe.run_one_serial_iter(batch, 0)

        base_avgs = [self._timed_run(batch, num_measure) for _ in range(num_rounds)]
        baseline = statistics.median(base_avgs)

        exposed: Dict[str, float] = {}
        for td in pipe._topo_order:
            pipe.enable_shortcut(td.name)
            pipe.run_one_serial_iter(batch, 0)  # caching iteration

            round_avgs = [
                self._timed_run(batch, num_measure) for _ in range(num_rounds)
            ]
            exposed[td.name] = max(0.0, baseline - statistics.median(round_avgs))

            pipe.disable_shortcut(td.name)

        return ProfileResult(baseline_s=baseline, exposed_s=exposed)

    def profile_many(
        self,
        batches: list,
        num_warmup: int = 3,
        num_measure: int = 10,
        num_rounds: int = 3,
    ) -> List[ProfileResult]:
        """Profile each batch independently, return one result per batch.

        Useful for understanding how exposed time varies across different
        data distributions or batch sizes.
        """
        return [
            self.profile(
                b, num_warmup=num_warmup, num_measure=num_measure, num_rounds=num_rounds
            )
            for b in batches
        ]
